#!/usr/bin/env python3
"""Собирает v1/servers/cstrike для статического мастера Xash3D (masterstatic).

Вход:
  upstream/ms.txt         - ip:port по строке (список из rawList)
  upstream/blacklist.txt  - ip, ip:port или CIDR по строке (зеркала, фейки)
  extra.txt               - свои серверы, всегда в списке: ip:port по строке (необязательно)
  own_blacklist.txt       - свои исключения (необязательно)
Выход:
  v1/servers/cstrike      - строки "gs ip:port" (протокол GoldSrc 48)
"""
import ipaddress
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "v1" / "servers" / "cstrike"
ADDR = re.compile(r"^(\d{1,3}(?:\.\d{1,3}){3}):(\d{1,5})$")


def lines(path):
    if not path.exists():
        return []
    out = []
    for raw in path.read_text(encoding="utf-8", errors="replace").splitlines():
        s = raw.split("#", 1)[0].strip()
        if s:
            out.append(s)
    return out


def parse_addr(s):
    m = ADDR.match(s)
    if not m:
        return None
    try:
        ip = ipaddress.IPv4Address(m.group(1))
    except ValueError:
        return None
    port = int(m.group(2))
    if not 1 <= port <= 65535:
        return None
    return ip, port


def load_blacklist(*paths):
    nets, addrs = [], set()
    for p in paths:
        for s in lines(p):
            try:
                if ":" in s:
                    a = parse_addr(s)
                    if a:
                        addrs.add(a)
                elif "/" in s:
                    nets.append(ipaddress.IPv4Network(s, strict=False))
                else:
                    nets.append(ipaddress.IPv4Network(s + "/32"))
            except ValueError:
                continue
    return nets, addrs


def main():
    ms = lines(ROOT / "upstream" / "ms.txt")
    if len(ms) < 100:
        print("ms.txt слишком короткий (%d строк), прерываю" % len(ms), file=sys.stderr)
        return 1

    nets, banned_addrs = load_blacklist(ROOT / "upstream" / "blacklist.txt", ROOT / "own_blacklist.txt")
    banned_ips = {n.network_address for n in nets if n.prefixlen == 32}
    wide = [n for n in nets if n.prefixlen != 32]

    def banned(ip, port):
        if (ip, port) in banned_addrs or ip in banned_ips:
            return True
        return any(ip in n for n in wide)

    result, skipped = set(), 0
    for s in ms:
        a = parse_addr(s)
        if not a:
            continue
        if banned(*a):
            skipped += 1
            continue
        result.add(a)

    # свои серверы: порядок как в extra.txt, они идут в файле первыми
    own = []
    for s in lines(ROOT / "extra.txt"):
        a = parse_addr(s)
        if a and a not in own:
            own.append(a)

    others = sorted(a for a in result if a not in set(own))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    body = "# own servers\n"
    body += "".join("gs %s:%d own\n" % (ip, port) for ip, port in own)
    body += "# community servers\n"
    body += "".join("gs %s:%d\n" % (ip, port) for ip, port in others)
    header = "# generated by scripts/build_list.py: %d servers (%d own, %d filtered by blacklist)\n" % (
        len(own) + len(others), len(own), skipped)
    OUT.write_text(header + body, encoding="utf-8")
    print(header.strip())
    return 0


if __name__ == "__main__":
    sys.exit(main())
